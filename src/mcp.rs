use rmcp::{
    ErrorData, RoleServer, ServerHandler,
    handler::server::tool::ToolCallContext,
    model::{
        CacheScope, CallToolRequestParams, CallToolResponse, CallToolResult, ContentBlock,
        ListToolsResult, PaginatedRequestParams, ProtocolVersion,
    },
    service::RequestContext,
    tool_handler,
};
use sqlx::SqlitePool;

use crate::{
    auth::Principal,
    authz::{ToolPermissions, load_tool_permissions},
};
#[derive(Clone)]
pub struct McpServer {
    pub(crate) pool: SqlitePool,
    pub(crate) analyst: Option<std::sync::Arc<crate::assessments::Analyst>>,
}

pub(crate) fn principal_from_context(
    context: &RequestContext<RoleServer>,
) -> Result<Principal, ErrorData> {
    context
        .extensions
        .get::<axum::http::request::Parts>()
        .and_then(|parts| parts.extensions.get::<Principal>())
        .cloned()
        .ok_or_else(|| ErrorData::internal_error("Authenticated identity is missing", None))
}

impl McpServer {
    pub fn new(pool: SqlitePool) -> Self {
        Self {
            pool,
            analyst: None,
        }
    }

    pub fn with_analyst(mut self, analyst: std::sync::Arc<crate::assessments::Analyst>) -> Self {
        self.analyst = Some(analyst);
        self
    }

    async fn permissions_for_request(
        &self,
        context: &RequestContext<RoleServer>,
    ) -> Result<(Principal, ToolPermissions), ErrorData> {
        let principal = principal_from_context(context)?;

        let permissions = load_tool_permissions(&self.pool, &principal)
            .await
            .map_err(|error| {
                tracing::error!(
                    %error,
                    tenant_id = %principal.tenant_id,
                    object_id = %principal.object_id,
                    "Tool permission lookup failed"
                );
                ErrorData::internal_error("Unable to check tool permissions", None)
            })?;
        Ok((principal, permissions))
    }
}

// Registers the router generated by #[tool_router] in tools.rs.
#[tool_handler]
impl ServerHandler for McpServer {
    fn get_info(&self) -> rmcp::model::ServerConfig {
        let mut capabilities = rmcp::model::ServerCapabilities::builder()
            .enable_tools()
            .build();

        capabilities.extensions =
            Some([(crate::assessments::CHUNKS.into(), Default::default())].into());

        rmcp::model::ServerConfig::new(capabilities).with_instructions(
            "For live project assessments, tell the user a fresh run_id, then call \
             assess_projects sequentially once per project, setting project_id and keeping \
             the same full ordered project_ids. Report each returned completion or failure \
             before starting the next project. Keep the turn open: if a call yields or is \
             still running, use the host's wait mechanism until it returns. Continue until \
             every selected project has an outcome; do not wait for another user prompt. \
             Progress notifications are optional UI updates, not intermediate tool results. \
             Treat only completed results as validated assessments. Each response contains \
             the cumulative saved run; do not repeat outcomes already reported. Advance \
             past failed projects and report their errors; retry each failed project at \
             most once unless the user asks for more. Use read_assessment_run to recover \
             results after a connection ends, then resume pending projects with the same \
             run_id and full ordered project_ids. Omit project_id only for a single batch \
             result or a client that consumes MCP progress directly.",
        )
    }

    async fn list_tools(
        &self,
        _request: Option<PaginatedRequestParams>,
        context: RequestContext<RoleServer>,
    ) -> Result<ListToolsResult, ErrorData> {
        let (principal, permissions) = self.permissions_for_request(&context).await?;

        let tools = Self::tool_router()
            .list_all()
            .into_iter()
            .filter(|tool| permissions.can_use(tool.name.as_ref()))
            .collect::<Vec<_>>();

        tracing::info!(
            tenant_id = %principal.tenant_id,
            object_id = %principal.object_id,
            allowed_tools = ?tools.iter().map(|tool| tool.name.as_ref()).collect::<Vec<_>>(),
            "MCP tool discovery authorized"
        );

        let mut result = ListToolsResult::with_all_items(tools);

        if context
            .protocol_version()
            .is_some_and(|v| v >= ProtocolVersion::V_2026_07_28)
        {
            result.ttl_ms = Some(0);
            result.cache_scope = Some(CacheScope::Private);
        }

        Ok(result)
    }

    async fn call_tool(
        &self,
        request: CallToolRequestParams,
        context: RequestContext<RoleServer>,
    ) -> Result<CallToolResponse, ErrorData> {
        let (principal, permissions) = self.permissions_for_request(&context).await?;

        if !permissions.can_use(request.name.as_ref()) {
            tracing::warn!(
                tenant_id = %principal.tenant_id,
                object_id = %principal.object_id,
                tool = %request.name,
                allowed = false,
                "MCP tool authorization denied"
            );
            return Ok(CallToolResult::error(vec![ContentBlock::text(
                "You do not have permissions to use this tool.",
            )])
            .into());
        }

        tracing::info!(
            tenant_id = %principal.tenant_id,
            object_id = %principal.object_id,
            tool = %request.name,
            allowed = true,
            "MCP tool authorization granted"
        );

        Self::tool_router()
            .call(ToolCallContext::new(self, request, context))
            .await
    }
}
